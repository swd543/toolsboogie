/*
 * The 20 per-path converter URLs (/convert/json-to-yaml, …) get their own
 * indexable meta so each search query lands on its own page.
 */
for (const pair of formatPairs()) {
  const { title, description } = pathMeta(pair);
  routeMeta[`/convert/${pair.slug}`] = { title, description, image: ogImage };
}
/**
 * JSON-LD per route: the home page advertises a SoftwareApplication suite,
 * each tool page its own WebApplication.
 */
export function jsonLdFor(route: string): Record<string, unknown> {
  const meta = routeMeta[route] ?? routeMeta['/']!;
  const base = {
    '@context': 'https://schema.org',
    name: site.name,
    url: canonicalFor(route),
    description: meta.description,
    image: meta.image,
  };
  if (route === '/') {
    return {
      ...base,
      '@type': 'WebApplication',
      applicationCategory: 'UtilityApplication',
      operatingSystem: 'Any',
      offers: { '@type': 'Offer', price: '0', priceCurrency: 'USD' },
    };
  }
  return {
    ...base,
    '@type': 'WebApplication',
    applicationCategory: 'UtilityApplication',
    applicationSubCategory: toolSubcategory(route),
    operatingSystem: 'Any',
    browserRequirements:
      'Requires JavaScript. Audio tools require a microphone; compass and level require device sensors.',
    offers: { '@type': 'Offer', price: '0', priceCurrency: 'USD' },
  };
}

function toolSubcategory(route: string): string {
  if (route === '/convert' || route.startsWith('/convert/')) {
    return 'Developer Tool';
  }
  switch (route) {
    case '/guitar-tuner':
      return 'Music Tuner';
    case '/json-format':
    case '/json-to-yaml':
    case '/yaml-format':
    case '/convert':
    case '/regex':
    case '/string-escape':
    case '/cron':
      return 'Developer Tool';
    case '/validators':
    case '/json-validator':
    case '/yaml-validator':
    case '/toml-validator':
    case '/ini-validator':
    case '/xml-validator':
      return 'Developer Tool';
    case '/time':
      return 'Reference';
    case '/jwt':
      return 'Security Tool';
    case '/compass':
      return 'Navigation';
    case '/ruler':
    case '/level':
      return 'Measurement';
    default:
      return 'Utility';
  }
}
